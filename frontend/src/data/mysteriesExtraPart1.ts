import type {
  CategorySlug,
  CompetingTheory,
  EvidenceStatus,
  MysteryInvestigation,
} from '../types/archive';

interface DossierSpec {
  slug: string;
  title: string;
  subtitle: string;
  summary: string;
  category: CategorySlug;
  secondaryCategories?: CategorySlug[];
  evidenceStatus: EvidenceStatus;
  evidenceRationale: string;
  region: string;
  locationName: string;
  lat: number;
  lng: number;
  precisionLabel: string;
  popularityScore: number;
  heroImage: string;
  what: string;
  where: string;
  when: string;
  narrative: string;
  whyMysterious: string[];
  timeline: Array<{ yearLabel: string; sortYear: number; title: string; description: string; significance: string }>;
  whatWeKnow: string[];
  evidenceTitle: string;
  evidenceOrigin: string;
  evidenceDate: string;
  evidenceFinding: string;
  theories: Array<{
    name: string;
    claim: string;
    supporting: string[];
    contradicting: string[];
    limitations: string;
    acceptance: CompetingTheory['scientificAcceptance'];
  }>;
  methods: string[];
  scientificNarrative: string;
  whatRemainsUnknown: string[];
  finalAssessment: string;
  sourceIds: string[];
}

export function buildDossier(spec: DossierSpec): MysteryInvestigation {
  return {
    slug: spec.slug,
    title: spec.title,
    subtitle: spec.subtitle,
    summary: spec.summary,
    category: spec.category,
    secondaryCategories: spec.secondaryCategories,
    evidenceStatus: spec.evidenceStatus,
    evidenceRationale: spec.evidenceRationale,
    region: spec.region,
    locationName: spec.locationName,
    coordinates: {
      lat: spec.lat,
      lng: spec.lng,
      precisionLabel: spec.precisionLabel,
    },
    readingTimeMinutes: 7,
    popularityScore: spec.popularityScore,
    updatedAt: '2026-11-20',
    featured: false,
    heroImage: spec.heroImage,
    imageAlt: `${spec.title} — archival editorial visual plate`,
    overview: {
      what: spec.what,
      where: spec.where,
      when: spec.when,
      narrative: spec.narrative,
    },
    whyMysterious: spec.whyMysterious,
    timeline: spec.timeline.map((t, idx) => ({
      id: `${spec.slug}-tl-${idx + 1}`,
      yearLabel: t.yearLabel,
      sortYear: t.sortYear,
      title: t.title,
      description: t.description,
      significance: t.significance,
    })),
    whatWeKnow: spec.whatWeKnow,
    originalEvidence: [
      {
        title: spec.evidenceTitle,
        recordType: 'Primary Record',
        date: spec.evidenceDate,
        origin: spec.evidenceOrigin,
        description: spec.what,
        measurementOrFinding: spec.evidenceFinding,
        sourceId: spec.sourceIds[0],
      },
    ],
    competingTheories: spec.theories.map((th, idx) => ({
      id: `${spec.slug}-th-${idx + 1}`,
      name: th.name,
      claim: th.claim,
      supportingEvidence: th.supporting,
      contradictingEvidence: th.contradicting,
      scientificLimitations: th.limitations,
      scientificAcceptance: th.acceptance,
      sourceIds: spec.sourceIds,
    })),
    scientificInvestigation: {
      methods: spec.methods,
      narrative: spec.scientificNarrative,
    },
    whatRemainsUnknown: spec.whatRemainsUnknown,
    finalAssessment: spec.finalAssessment,
    sourceIds: spec.sourceIds,
  };
}

